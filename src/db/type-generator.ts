import type { Field, Model, Schema, TypeExpr, View } from '../schema-dsl/ast.js';
import {
  fieldHasAttribute,
  getModelNames,
  getStoredFields,
} from '../sql-generator/utils/ast-helpers.js';
import { toClientKey } from './utils/naming.js';

export class TypeGenerator {
  constructor(private readonly schema: Schema) {}

  generate(): string {
    const enumBlocks = this.schema.enums.map((enumDef) => this.generateEnumType(enumDef.name, enumDef.values));
    const includeArgsBlocks = this.schema.models.map((model) => this.generateIncludeArgs(model));
    const includeBlocks = this.schema.models.map((model) => this.generateInclude(model));
    const modelBlocks = this.schema.models.flatMap((model) => this.generateModelTypes(model));
    const viewBlocks = this.schema.views.flatMap((view) => this.generateViewTypes(view));

    return [
      '// Auto-generated by TypeGenerator. Do not edit manually.',
      '',
      ...enumBlocks,
      ...modelBlocks,
      ...viewBlocks,
      ...includeArgsBlocks,
      ...includeBlocks,
    ].join('\n');
  }

  private generateEnumType(name: string, values: string[]): string {
    const union = values.map((value) => `'${value}'`).join(' | ');
    return `export type ${name} = ${union};\n`;
  }

  private generateViewTypes(view: View): string[] {
    return [
      this.generateEntityInterface(view.name, view.columns),
      this.generateWhereInput(view.name, view.columns),
      this.generateOrderByInput(view.name, view.columns),
      '',
    ];
  }

  private generateModelTypes(model: Model): string[] {
    const modelNames = getModelNames(this.schema);
    const storedFields = getStoredFields(model, modelNames);

    return [
      this.generateEntityInterface(model.name, storedFields),
      this.generateCreateInput(model.name, storedFields),
      this.generateUpdateInput(model.name, storedFields),
      this.generateWhereInput(model.name, storedFields),
      this.generateOrderByInput(model.name, storedFields),
      '',
    ];
  }

  private generateEntityInterface(modelName: string, fields: Field[]): string {
    const lines = fields.map((field) => `  ${field.name}: ${this.toTsType(field, 'entity')};`);
    return `export interface ${modelName} {\n${lines.join('\n')}\n}\n`;
  }

  private generateCreateInput(modelName: string, fields: Field[]): string {
    const lines = fields
      .filter((field) => !fieldHasAttribute(field, 'id'))
      .map((field) => {
        const optionalMarker = field.type.optional || fieldHasAttribute(field, 'default') ? '?' : '';
        return `  ${field.name}${optionalMarker}: ${this.toTsType(field, 'input')};`;
      });

    return `export interface ${modelName}CreateInput {\n${lines.join('\n')}\n}\n`;
  }

  private generateUpdateInput(modelName: string, fields: Field[]): string {
    const lines = fields
      .filter((field) => !fieldHasAttribute(field, 'id'))
      .map((field) => `  ${field.name}?: ${this.toTsType(field, 'input')};`);

    return `export interface ${modelName}UpdateInput {\n${lines.join('\n')}\n}\n`;
  }

  private generateWhereInput(modelName: string, fields: Field[]): string {
    const filterableFields = fields.filter((field) => this.isFilterable(field));
    const lines = filterableFields.map((field) => `  ${field.name}?: ${this.toWhereFieldType(field)};`);
    lines.push('  AND?: ' + modelName + 'WhereInput[];');
    lines.push('  OR?: ' + modelName + 'WhereInput[];');
    lines.push('  NOT?: ' + modelName + 'WhereInput;');

    return `export interface ${modelName}WhereInput {\n${lines.join('\n')}\n}\n`;
  }

  private generateOrderByInput(modelName: string, fields: Field[]): string {
    const lines = fields.map((field) => `  ${field.name}?: 'asc' | 'desc';`);
    return `export interface ${modelName}OrderByInput {\n${lines.join('\n')}\n}\n`;
  }

  private generateIncludeArgs(model: Model): string {
    return `export interface ${model.name}IncludeArgs {\n  where?: ${model.name}WhereInput;\n  orderBy?: ${model.name}OrderByInput | ${model.name}OrderByInput[];\n  take?: number;\n  skip?: number;\n  include?: ${model.name}Include;\n}\n`;
  }

  private generateInclude(model: Model): string {
    const modelNames = getModelNames(this.schema);
    const relationFields = model.fields.filter((field) => modelNames.has(field.type.name));

    if (relationFields.length === 0) {
      return `export interface ${model.name}Include {}\n`;
    }

    const lines = relationFields.map(
      (field) => `  ${field.name}?: boolean | ${field.type.name}IncludeArgs;`,
    );

    return `export interface ${model.name}Include {\n${lines.join('\n')}\n}\n`;
  }

  private toTsType(field: Field, mode: 'entity' | 'input'): string {
    const base = this.mapTypeExpr(field.type);

    if (field.type.optional) {
      return `${base} | null`;
    }

    if (mode === 'input' && fieldHasAttribute(field, 'default')) {
      return base;
    }

    return base;
  }

  private mapTypeExpr(type: TypeExpr): string {
    const enumType = this.schema.enums.find((enumDef) => enumDef.name === type.name);
    if (enumType) {
      return type.name;
    }

    if (type.array && type.name === 'TEXT') {
      return 'string[]';
    }

    switch (type.name) {
      case 'UUID':
      case 'VARCHAR':
      case 'TEXT':
        return 'string';
      case 'INTEGER':
      case 'SERIAL':
      case 'SMALLINT':
      case 'REAL':
      case 'DOUBLE':
        return 'number';
      case 'BIGINT':
      case 'BIGSERIAL':
      case 'DECIMAL':
      case 'NUMERIC':
        return 'string';
      case 'BOOLEAN':
        return 'boolean';
      case 'TIMESTAMP':
      case 'DATE':
      case 'TIME':
        return 'Date';
      case 'INTERVAL':
        return 'string';
      case 'JSONB':
        return 'Record<string, unknown>';
      case 'BYTEA':
        return 'Buffer';
      case 'POINT':
        return 'unknown';
      default:
        return 'unknown';
    }
  }

  private isFilterable(field: Field): boolean {
    const typeName = field.type.name;
    return !this.schema.models.some((model) => model.name === typeName);
  }

  private toWhereFieldType(field: Field): string {
    const base = this.mapTypeExpr(field.type);
    const scalar = field.type.optional ? `${base} | null` : base;
    const filters: string[] = [`{ equals: ${scalar} }`];
    const isStringType = ['UUID', 'VARCHAR', 'TEXT'].includes(field.type.name);
    const isEnumType = this.schema.enums.some((enumDef) => enumDef.name === field.type.name);

    if (isStringType) {
      filters.push(`{ contains: string }`, `{ startsWith: string }`, `{ endsWith: string }`);
    }

    if (isEnumType) {
      filters.push(`{ in: ${base}[] }`);
    }

    if (['INTEGER', 'SERIAL', 'SMALLINT', 'DECIMAL'].includes(field.type.name)) {
      filters.push(
        `{ gt: ${base} }`,
        `{ gte: ${base} }`,
        `{ lt: ${base} }`,
        `{ lte: ${base} }`,
      );
    }

    if (field.type.name === 'BOOLEAN') {
      return scalar;
    }

    return [scalar, ...filters].join(' | ');
  }
}

export function generateDbTypes(schema: Schema): string {
  return new TypeGenerator(schema).generate();
}

export function getClientExportName(modelName: string): string {
  return toClientKey(modelName);
}
